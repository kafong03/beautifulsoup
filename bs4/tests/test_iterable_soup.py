import types
from bs4 import BeautifulSoup, Comment, Doctype, NavigableString, Tag
from bs4.tests import SoupTest

class TestIterableSoup(SoupTest):
    def test_empty_document(self):
        # Iterating over an empty BeautifulSoup object yields no items (does not raise an error)
        soup = self.soup("")
        assert list(soup) == []
    

    def test_preorder_node_traversal(self):
        # Iterating over a BeautifulSoup object traverses over nodes in preorder order
        data = "<p>262P<h1><b>Milestone4</b></h1>With Professor Lopes</p>"
        soup = self.soup(data)
        nodes = list(soup)

        assert len(nodes) == 6
        assert isinstance(nodes[0], Tag) and nodes[0].name == "p"
        assert isinstance(nodes[1], NavigableString) and str(nodes[1]) == "262P"
        assert isinstance(nodes[2], Tag) and nodes[2].name == "h1"
        assert isinstance(nodes[3], Tag) and nodes[3].name == "b"
        assert isinstance(nodes[4], NavigableString) and str(nodes[4]) == "Milestone4"
        assert isinstance(nodes[5], NavigableString) and str(nodes[5]) == "With Professor Lopes"

    
    def test_multiple_top_level_siblings(self):
        # Iterating over a BeautifulSoup object with multiple sibling root elements properly lists yields them in order.
        data = "<div>First</div><p>Second</p><span>Third</span>"
        soup = self.soup(data)
        page_element_strs = [node.name if isinstance(node, Tag) else str(node) for node in soup]

        assert page_element_strs == ["div", "First", "p", "Second", "span", "Third"]


    def test_mixed_page_elements(self):
        # Iterating over a BeautifulSoup object with different PageElements (DOCTYPE, comments, Tags, text, etc.) should yield all PageElements
        data = "<!DOCTYPE html><!-- header comment --><div><p>Text</p></div>"
        soup = self.soup(data)

        assert any(isinstance(node, Doctype) for node in soup)
        assert any(isinstance(node, Comment) and str(node) == " header comment " for node in soup)
        assert [node.name for node in soup if isinstance(node, Tag)] == ["div", "p"]

    
    def test_yield_on_demand(self):
        # Creating an Iterator for a BeautifulSoup object produces one node at a time when iter.next() is called
        data = "<p>262P<h1><b>Milestone4</b></h1>With Professor Lopes</p>"
        soup = self.soup(data)
        iterator = iter(soup)

        assert str(next(iterator)) == "<p>262P<h1><b>Milestone4</b></h1>With Professor Lopes</p>"
        assert str(next(iterator)) == "262P"
        assert str(next(iterator)) == "<h1><b>Milestone4</b></h1>"

    
    # Additional Test generated by Google Gemini 4 Hydrogen
    def test_tag_iter_unaffected(self):
        # Iterating over an individual Tag still yields only its direct children (Tag.__iter__ preserved) 
        data = "<ul><li><b>Item 1</b></li><li><i>Item 2</i></li></ul>"
        soup = self.soup(data)
        ul_children = list(soup.ul)

        assert len(ul_children) == 2
        assert all(isinstance(child, Tag) and child.name == "li" for child in ul_children)
        

